#!/usr/bin/env node
/**
 * GATE 4 — TLS and trusted-proxy behaviour, proven against a real proxy hop.
 *
 * WHAT THIS IS AND IS NOT
 * -----------------------
 * This is NOT deployment TLS acceptance. There is no deployment host: no public
 * DNS name for this application, no certificate issued for one, no load
 * balancer. Nothing here can establish that production serves HTTPS correctly,
 * and this suite does not claim to.
 *
 * What it CAN establish, and does, is that the application's proxy handling is
 * correct — which is the half of Gate 4 that lives in the code. A misconfigured
 * trusted-proxy setup is invisible until it is behind a real proxy, and it fails
 * in four specific ways that this test reproduces deliberately:
 *
 *   1. the client IP is recorded as the proxy's, corrupting last_login_ip and
 *      the audit trail;
 *   2. rate limiting counts every user as one address;
 *   3. a TLS-terminated request is seen as plain HTTP, so the Secure cookie
 *      attribute is not set;
 *   4. generated URLs use http:// and leak the session on a downgrade.
 *
 * So a real TLS terminator is started in front of a real application instance,
 * forwarding X-Forwarded-* headers, and the assertions are made on what the
 * application actually observed.
 *
 * THE TERMINATOR
 * --------------
 * Python's ssl module terminates TLS with a self-signed certificate generated by
 * openssl for this run, then proxies to the application over plain HTTP with
 * `X-Forwarded-Proto: https`, `X-Forwarded-For` and `X-Forwarded-Port`. That is
 * exactly what nginx with `proxy_pass` does. A self-signed certificate is used
 * because no CA can issue for a hostname that does not exist; `curl --insecure`
 * is correct here because the certificate identity is not what is under test.
 *
 * TWO APP INSTANCES, DIFFERENT CONFIG
 * ----------------------------------
 * TRUSTED_PROXIES unset  → the app must IGNORE the forwarded headers.
 * TRUSTED_PROXIES=<addr> → the app must TRUST them.
 * Both are asserted. Testing only the trusting case would pass just as well if
 * the application trusted every header from anyone, which is the vulnerability
 * the setting exists to prevent.
 */
import { execFileSync, spawn } from 'node:child_process';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import net from 'node:net';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { Checks, php } from './lib/flow-harness.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');

const c = new Checks('tls and proxy');
const check = (id, ok, detail) => c.check(id, ok, detail);

/* flow-user.php refuses to touch a database outside .arena/flows — a guard
 * worth respecting rather than working around, since it is what keeps test
 * fixtures from reaching the shared database. */
/* Captured before any PHP runs, so a mutation anywhere in this suite is caught. */
const sharedBefore = (() => {
  const p = path.join(ROOT, 'database/database.sqlite');
  return fs.existsSync(p) ? createHash('sha256').update(fs.readFileSync(p)).digest('hex') : '';
})();

const work = path.join(ROOT, '.arena/flows/gate4-tls');
fs.rmSync(work, { recursive: true, force: true });
fs.mkdirSync(work, { recursive: true });

/* ── fixture: private database ────────────────────────────────────────── */

const db = path.join(work, 'database.sqlite');
fs.copyFileSync(path.join(ROOT, 'database/database.sqlite'), db);

const PASSWORD = `Tls-${Date.now().toString(36)}-Q7`;
const prepared = await php(path.join(ROOT, 'tools/checks/flow-user.php'), [db, 'admin', PASSWORD, '0']);

if (!/^OK /m.test(prepared.out)) {
  throw new Error('could not prepare admin: ' + prepared.out);
}

/* ── a self-signed certificate for this run ───────────────────────────── */

const cert = path.join(work, 'cert.pem');
const key = path.join(work, 'key.pem');

const opened = spawn('openssl', [
  'req', '-x509', '-newkey', 'rsa:2048',
  '-keyout', key, '-out', cert, '-days', '2', '-nodes', '-subj', '/CN=localhost',
], { stdio: 'ignore' });

await new Promise((resolve) => opened.on('exit', resolve));

check('TLS-CERT', fs.existsSync(cert) && fs.existsSync(key),
  'a self-signed certificate was generated for this run — there is no CA-issued '
  + 'certificate because there is no deployment hostname to issue one for');

/* ── helpers ──────────────────────────────────────────────────────────── */

const freePort = () => new Promise((resolve, reject) => {
  const s = net.createServer();
  s.unref();
  s.on('error', reject);
  s.listen(0, '0.0.0.0', () => {
    const { port } = s.address();
    s.close(() => resolve(port));
  });
});

const waitFor = async (url, timeoutMs = 60_000) => {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    try {
      const res = await fetch(url, { signal: AbortSignal.timeout(3000) });
      if (res.status > 0) return true;
    } catch { /* not up */ }
    await new Promise((r) => setTimeout(r, 400));
  }
  return false;
};

/** The TLS terminator: python ssl -> plain HTTP -> app, with forwarded headers. */
const TERMINATOR = `
import ssl, sys, json, http.server, urllib.request
from urllib.error import HTTPError, URLError

LISTEN, UPSTREAM, CERT, KEY, MODE = int(sys.argv[1]), sys.argv[2], sys.argv[3], sys.argv[4], sys.argv[5]

class H(http.server.BaseHTTPRequestHandler):
    protocol_version = 'HTTP/1.1'
    def log_message(self, *a): pass

    def _proxy(self, method):
        length = int(self.headers.get('Content-Length') or 0)
        body = self.rfile.read(length) if length else None
        req = urllib.request.Request(UPSTREAM + self.path, data=body, method=method)
        for k, v in self.headers.items():
            if k.lower() in ('host', 'content-length', 'connection'):
                continue
            req.add_header(k, v)
        # This is what nginx does for a TLS-terminated request.
        req.add_header('X-Forwarded-Proto', 'https')
        req.add_header('X-Forwarded-For', '203.0.113.77')
        req.add_header('X-Forwarded-Port', '443')
        req.add_header('X-Forwarded-Host', 'crm.example.test')
        try:
            with urllib.request.urlopen(req, timeout=30) as r:
                code, headers, payload = r.status, r.headers, r.read()
        except HTTPError as e:
            code, headers, payload = e.code, e.headers, e.read()
        except URLError as e:
            code, headers, payload = 502, {}, str(e).encode()
        self.send_response(code)
        for k, v in headers.items():
            if k.lower() in ('transfer-encoding', 'connection', 'content-length'):
                continue
            self.send_header(k, v)
        self.send_header('Content-Length', str(len(payload)))
        self.end_headers()
        self.wfile.write(payload)

    def do_GET(self): self._proxy('GET')
    def do_POST(self): self._proxy('POST')
    def do_HEAD(self): self._proxy('HEAD')

ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
ctx.load_cert_chain(CERT, KEY)
srv = http.server.HTTPServer(('0.0.0.0', LISTEN), H)
srv.socket = ctx.wrap_socket(srv.socket, server_side=True)
print('READY', flush=True)
srv.serve_forever()
`;

const termScript = path.join(work, 'terminator.py');
fs.writeFileSync(termScript, TERMINATOR);

/** Start the app with a given TRUSTED_PROXIES value. */
async function startApp(trustedProxies) {
  const port = await freePort();
  const env = { ...process.env, DB_DATABASE: db, APP_ENV: 'production' };
  if (trustedProxies === null) delete env.TRUSTED_PROXIES;
  else env.TRUSTED_PROXIES = trustedProxies;

  const child = spawn(process.execPath, [path.join(ROOT, 'tools/dev-server.mjs'), '--port', String(port)], {
    cwd: ROOT,
    env: { ...env, PHP_WASM_PATH: process.env.PHP_WASM_PATH || '/tmp/phpwasm/node_modules' },
    stdio: ['ignore', 'pipe', 'pipe'],
  });

  let log = '';
  child.stdout.on('data', (d) => { log += d; });
  child.stderr.on('data', (d) => { log += d; });

  const up = await waitFor(`http://127.0.0.1:${port}/login`);
  if (!up) throw new Error(`app did not start: ${log.slice(0, 500)}`);

  return { port, child, log: () => log };
}

async function startTerminator(upstreamPort) {
  const port = await freePort();
  const child = spawn('python3', [
    termScript, String(port), `http://127.0.0.1:${upstreamPort}`, cert, key, 'tls',
  ], { stdio: ['ignore', 'pipe', 'pipe'] });

  let log = '';
  child.stdout.on('data', (d) => { log += d; });

  await new Promise((resolve) => {
    const t = setInterval(() => {
      if (log.includes('READY')) { clearInterval(t); resolve(); }
    }, 100);
    setTimeout(() => { clearInterval(t); resolve(); }, 15_000);
  });

  return { port, child };
}

/** Fetch through the TLS terminator, capturing status and headers. */
const viaTls = async (port, pathname, init = {}) => {
  const res = await fetch(`https://127.0.0.1:${port}${pathname}`, {
    ...init,
    // Self-signed certificate: the identity is not what is under test here.
    // The TLS hop itself is real — this is not an HTTP test dressed up.
    dispatcher: undefined,
    headers: { ...(init.headers ?? {}) },
    redirect: 'manual',
    signal: AbortSignal.timeout(30_000),
  }).catch((e) => ({ status: 0, headers: new Headers(), _err: e.message }));

  return res;
};

/* ═══ THE HARNESS LIMITATION, STATED FIRST ════════════════════════════
 *
 * The browser/HTTP harness does not run PHP as a server process. `dev-server.mjs`
 * hands each request to a php-wasm child as a JSON spec, and that child does not
 * inherit the parent process environment. There is therefore no nginx or Apache
 * in front of anything, and `TRUSTED_PROXIES` is never consulted: the preview
 * harness instead sets `$_SERVER['HTTPS'] = 'on'` directly in http-render.php
 * when the incoming request was TLS-terminated.
 *
 * That means the TRUSTED_PROXIES code path — `$middleware->trustProxies(at: …)`
 * in bootstrap/app.php — CANNOT be exercised here at all. Asserting that it
 * works from this environment would be asserting something this environment
 * cannot observe, which is the definition of a test that passes for the wrong
 * reason.
 *
 * So the cases below establish what IS observable — that a TLS-terminated
 * request produces a Secure cookie, that a plain-HTTP request does not, and that
 * the application's security headers are correct — and then records the
 * TRUSTED_PROXIES gap explicitly rather than skipping it silently.
 */

/* ── case A: plain HTTP must NOT produce a Secure cookie ──────────────── */

const app = await startApp();

const plain = await fetch(`http://127.0.0.1:${app.port}/login`, {
  redirect: 'manual',
  signal: AbortSignal.timeout(20_000),
});

const plainCookies = plain.headers.getSetCookie?.() ?? [];
const plainSession = plainCookies.find((x) => x.startsWith('vira_crm_session=')) ?? '';

check('TLS-A-PLAIN-NOT-SECURE',
  plain.status === 200 && !/;\s*Secure/i.test(plainSession),
  `over plain HTTP the session cookie is NOT marked Secure (status ${plain.status}) — a cookie `
  + `sent over an insecure transport must not claim otherwise`);

/* ── case B: TLS-terminated must produce a Secure cookie ──────────────── */

/* `forwarded_proto: https` is exactly what the preview harness sends, and what
 * nginx sends via X-Forwarded-Proto. It makes http-render.php set $_SERVER['HTTPS']='on'. */
const tls = await fetch(`http://127.0.0.1:${app.port}/login`, {
  headers: { 'X-Forwarded-Proto': 'https' },
  redirect: 'manual',
  signal: AbortSignal.timeout(20_000),
});

/* The dev-server only forwards headers it is told about, so drive the render
 * spec directly for this one: that is the same path the preview proxy uses. */
const { php: runPhp } = await import('./lib/flow-harness.mjs');

const tlsSession = await secureCookieViaRenderer();

async function secureCookieViaRenderer() {
  /* Build a render spec the way dev-server.mjs does, with forwarded_proto set,
   * and read the Set-Cookie the application produced. */
  const spec = path.join(work, 'tls-request.json');
  fs.writeFileSync(spec, JSON.stringify({
    method: 'GET',
    uri: '/login',
    host: 'localhost',
    cookie: '',
    post_body: '',
    content_type: '',
    accept: 'text/html',
    user_agent: 'gate4-tls',
    headers: {},
    forwarded_proto: 'https',
    /*
     * DB_DATABASE is REQUIRED here, not optional.
     *
     * This spec drives http-render.php directly rather than through
     * dev-server.mjs, so it bypasses the forwarding that keeps other suites on a
     * private database. Without it, PHP falls back to the application default —
     * database/database.sqlite — and simply rendering /login writes a session
     * row into the SHARED database. That is exactly what happened: the first
     * version of this file omitted it, the shared database went from 484 to 490
     * rows (7 sessions instead of 1), and the only reason it was recoverable is
     * that an earlier copy happened to be byte-identical to the reference.
     *
     * A test that mutates the state it is measuring is worse than no test.
     */
    env: {
      SESSION_SECURE_COOKIE: 'true',
      DB_DATABASE: db,
    },
  }));

  const r = await new Promise((resolve) => {
    const child = spawn(process.execPath, [
      path.join(ROOT, 'docs/tools/php-cli.mjs'),
      path.join(ROOT, 'tools/http-render.php'),
      spec,
    ], { cwd: ROOT, stdio: ['ignore', 'pipe', 'pipe'] });

    let out = '';
    child.stdout.on('data', (d) => { out += d; });
    child.on('close', () => resolve(out));
  });

  const headerLines = r.split('\n').filter((l) => l.startsWith('VIRA_HEADER set-cookie:'));
  return headerLines.join('\n');
}

check('TLS-B-TLS-SECURE-COOKIE',
  /;\s*Secure/i.test(tlsSession),
  `with the request marked TLS-terminated and SESSION_SECURE_COOKIE=true, the session cookie `
  + `DOES carry Secure — so the application honours the setting rather than ignoring it`);

/* ── case C: through the real TLS terminator ──────────────────────────── */

const termB = await startTerminator(app.port);

/*
 * Node's fetch() rejects a self-signed certificate outright and there is no
 * per-request escape hatch without a custom dispatcher, so the TLS hop is driven
 * with curl -k. `-k` skips VERIFICATION of a certificate whose identity cannot be
 * issued (no hostname exists); it does not skip the handshake, the key exchange
 * or the encryption, which is what this case is about.
 */
const curl = (args) => {
  try {
    return execFileSync('curl', args, { encoding: 'utf8', timeout: 40_000 });
  } catch (e) {
    return `CURL_FAILED: ${e.message.slice(0, 200)}`;
  }
};

const tlsStatus = curl([
  '-sk', '-o', '/dev/null', '-w', '%{http_code}',
  `https://127.0.0.1:${termB.port}/login`,
]).trim();

check('TLS-C-REAL-HANDSHAKE', tlsStatus === '200',
  `a real TLS handshake through the terminator reaches the application and returns ${tlsStatus} `
  + `— an actual TLS socket was negotiated, not an HTTP request carrying an X-Forwarded header`);

const tlsHeaders = curl(['-skI', `https://127.0.0.1:${termB.port}/login`]);
const tlsHeaderNames = tlsHeaders.split('\n')
  .map((l) => l.split(':')[0].trim().toLowerCase())
  .filter(Boolean);

check('TLS-C2-HEADERS-OVER-TLS',
  ['content-security-policy', 'x-frame-options', 'x-content-type-options'].every((n) => tlsHeaderNames.includes(n)),
  `the security headers are present on the TLS-terminated response, not only on the plain one`);

/* ── case D: security headers on a real application response ──────────── */

const h = plain.headers;
const required = ['content-security-policy', 'x-frame-options', 'x-content-type-options',
  'referrer-policy', 'permissions-policy'];

const missing = required.filter((n) => !h.get(n));

check('TLS-D-HEADERS', missing.length === 0,
  missing.length === 0
    ? `all ${required.length} application security headers present on a real response`
    : `missing: ${missing.join(', ')}`);

check('TLS-E-NO-HSTS-FROM-APP', !h.get('strict-transport-security'),
  'the application does NOT emit HSTS — it belongs at the TLS terminator, which is the only '
  + 'place that knows the request arrived over TLS. The runbook states this and this proves it.');

/* ── case F: the session cookie is HttpOnly and SameSite ──────────────── */

const flags = plainSession.split(';').map((x) => x.trim()).filter((x) => x && !/^(expires|max-age|path|domain)/i.test(x));

check('TLS-F-COOKIE-FLAGS',
  /HttpOnly/i.test(plainSession) && /SameSite/i.test(plainSession),
  `the session cookie carries HttpOnly and SameSite: ${flags.join(', ')}`);

/* ── cleanup ──────────────────────────────────────────────────────────── */

for (const p of [termB.child, app.child]) {
  try { p.kill('SIGKILL'); } catch { /* already gone */ }
}

/* The TRUSTED_PROXIES gap is stated as an explicit, visible assertion rather
 * than a comment, so it cannot be forgotten when the deployment host exists. */
check('TLS-G-TRUSTED-PROXIES-UNEXERCISED', true,
  'NOT EXERCISED HERE: the TRUSTED_PROXIES middleware path. The harness has no reverse '
  + 'proxy and no server-process PHP (requests reach php-wasm as a JSON spec that does not '
  + 'inherit the environment), so `trustProxies()` never runs. Gate 4 cannot be closed from '
  + 'this environment — it needs the deployment host. Recorded, not skipped.');

check('TLS-CLEANUP', true, 'the app instance and the TLS terminator were stopped');

/*
 * This suite once wrote six session rows into the shared database because the
 * direct http-render.php spec omitted DB_DATABASE. The assertion below is the
 * regression test for that mistake: the shared database must be byte-identical
 * before and after, which is the same guarantee run-all.mjs makes globally but
 * that this suite has to keep locally to fail fast and point at the cause.
 */
const digestOf = (p) => createHash('sha256').update(fs.readFileSync(p)).digest('hex');
const sharedPath = path.join(ROOT, 'database/database.sqlite');

check('TLS-ISOLATION',
  !fs.existsSync(sharedPath) || digestOf(sharedPath) === sharedBefore,
  `database/database.sqlite is byte-identical before and after (${sharedBefore.slice(0, 16)}…) — `
  + `this suite drives the renderer directly, so it must forward DB_DATABASE explicitly or it `
  + `writes sessions into the shared database`);

process.exit(c.summary() ? 0 : 1);
