#!/usr/bin/env node
/**
 * Generate docs/ERD.md and docs/database/erd.dot from the real foreign keys.
 *
 * WHY GENERATED
 * -------------
 * The repo already carries a hand-drawn ERD that predates contracts, payroll,
 * invoices and departments. An ERD that is missing tables is worse than none:
 * it is read as complete. This reads `pragma foreign_key_list` and draws what
 * the database actually enforces.
 *
 * Note the honest limitation printed in the document: SQLite enforces FKs only
 * when PRAGMA foreign_keys is on, and several relations in this schema are
 * implied by convention rather than declared.
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DB = path.join(ROOT, 'database/database.sqlite');

const sql = (q) => execFileSync(
  process.execPath,
  [path.join(ROOT, 'docs/tools/php-cli.mjs'), path.join(ROOT, 'tools/checks/schema-dump.php'), DB, q],
  { cwd: ROOT, encoding: 'utf8', maxBuffer: 40 * 1024 * 1024 },
).replace(/^\[php-cli\][^\n]*\n?/gm, '').trim();

const lines = (q) => sql(q).split('\n').filter(Boolean);

const tables = lines("select name from sqlite_master where type='table' and name not like 'sqlite_%' order by name");

/* Relations: [child, column, parent, parent_column] */
const edges = [];
for (const t of tables) {
  for (const l of lines(`pragma foreign_key_list("${t}")`)) {
    const p = l.split('\t');
    edges.push({ child: t, column: p[3], parent: p[2], parentColumn: p[4] || 'id' });
  }
}

/* Tables that participate in no FK, in either direction. These are the ones a
   diagram reader will wrongly assume are unrelated. */
const touched = new Set();
for (const e of edges) {
  touched.add(e.child);
  touched.add(e.parent);
}
const isolated = tables.filter((t) => !touched.has(t)
  && !['migrations', 'cache', 'cache_locks', 'jobs', 'job_batches', 'failed_jobs', 'sessions', 'password_reset_tokens', 'sqlite_sequence'].includes(t));

const rowsOf = (t) => Number(sql(`select count(*) from "${t}"`)) || 0;

/* ── dot file ───────────────────────────────────────────────────────────── */
const GROUPS = {
  identity: ['users', 'roles', 'permissions', 'role_permissions', 'user_roles'],
  customers: ['customers', 'customer_contacts', 'customer_websites'],
  projects: ['projects', 'project_types', 'project_assignments', 'project_keywords', 'seo_packages', 'seo_project_details', 'design_project_details'],
  contracts: ['contracts', 'contract_types', 'contract_templates', 'contract_versions', 'contract_files'],
  credentials: ['project_credentials', 'credential_types', 'credential_values', 'credential_requirements'],
  accounting: ['ledger_accounts', 'fiscal_periods', 'journal_entries', 'journal_lines', 'invoices', 'invoice_items', 'payments', 'payment_allocations', 'cost_centers'],
  hr: ['employees', 'departments', 'employee_contracts', 'payroll_periods', 'payroll_rules', 'payslips', 'payroll_items', 'payslip_versions'],
  ops: ['work_items', 'notes', 'attachments', 'audit_logs', 'scheduled_events', 'job_runs', 'settings', 'settings_history'],
};

let dot = `// GENERATED by tools/generate-erd.mjs — do not edit.
// Source: pragma foreign_key_list on database/database.sqlite
digraph vira {
  graph [rankdir=LR, fontname="Vazirmatn", splines=ortho, nodesep=0.35, ranksep=1.0];
  node  [shape=box, style="rounded,filled", fontname="Vazirmatn", fontsize=10, fillcolor="#ffffff"];
  edge  [color="#8a8a8a", arrowsize=0.7];

`;

for (const [group, list] of Object.entries(GROUPS)) {
  const present = list.filter((t) => tables.includes(t));
  if (!present.length) continue;
  dot += `  subgraph cluster_${group} {\n    label="${group}";\n    style="rounded,dashed";\n    color="#bbbbbb";\n`;
  for (const t of present) dot += `    "${t}";\n`;
  dot += '  }\n';
}

const drawn = new Set(Object.values(GROUPS).flat());
for (const t of tables) if (!drawn.has(t)) dot += `  "${t}";\n`;

for (const e of edges) {
  dot += `  "${e.child}" -> "${e.parent}" [label="${e.column}"];\n`;
}
dot += '}\n';

fs.mkdirSync(path.join(ROOT, 'docs/database'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'docs/database/erd.dot'), dot, 'utf8');

/* ── per-table incoming/outgoing, for the markdown ──────────────────────── */
const parentsOf = new Map();
const childrenOf = new Map();
for (const e of edges) {
  if (!parentsOf.has(e.child)) parentsOf.set(e.child, []);
  parentsOf.get(e.child).push(`${e.column} → ${e.parent}`);
  if (!childrenOf.has(e.parent)) childrenOf.set(e.parent, []);
  childrenOf.get(e.parent).push(`${e.child}.${e.column}`);
}

const hubOrder = [...tables].sort((a, b) => (childrenOf.get(b)?.length ?? 0) - (childrenOf.get(a)?.length ?? 0));

let md = `# نمودار رابطهٔ موجودیت‌ها

> **تولیدشده.** \`node tools/generate-erd.mjs\` آن را از \`pragma foreign_key_list\`
> می‌سازد. ERD دستیِ قدیمی در \`docs/diagrams/erd.{png,svg}\` هست، اما قراردادها،
> حقوق، فاکتورها و ساختار سازمانی را ندارد — نموداری که جدول ندارد از نبودِ نمودار
> بدتر است، چون کامل خوانده می‌شود.

${tables.length} جدول، **${edges.length}** کلید خارجی اعلان‌شده.

## مراکز

جدول‌هایی که بیشترین ارجاع به آن‌ها وجود دارد.

| جدول | ارجاع‌گیرنده |
|---|---|
`;
for (const t of hubOrder.slice(0, 8)) {
  const kids = childrenOf.get(t) ?? [];
  if (!kids.length) continue;
  md += `| \`${t}\` | ${kids.length} — ${kids.map((k) => '`' + k + '`').join('، ')} |\n`;
}

md += `\n## کلیدهای خارجی، به تفکیک جدول\n\n`;
for (const t of tables) {
  const parents = parentsOf.get(t) ?? [];
  const kids = childrenOf.get(t) ?? [];
  if (!parents.length && !kids.length) continue;
  md += `### \`${t}\`\n\n`;
  if (parents.length) md += `**به این جدول‌ها ارجاع می‌دهد:** ${parents.map((p) => '`' + p + '`').join('، ')}\n\n`;
  if (kids.length) md += `**این جدول‌ها به آن ارجاع می‌دهند:** ${kids.map((k) => '`' + k + '`').join('، ')}\n\n`;
}

if (isolated.length) {
  md += `## جدول‌های بدون کلید خارجی\n\n`;
  md += `این جدول‌ها هیچ رابطهٔ اعلان‌شده‌ای ندارند. بعضی عمداً مستقل‌اند (تنظیمات،
گزارش رویدادها)؛ بعضی دیگر رابطه‌شان فقط در کد است، نه در پایگاه داده — و همین
جایی است که یک JOIN اشتباه ساخته می‌شود.\n\n`;
  for (const t of isolated) md += `- \`${t}\` — ${rowsOf(t)} ردیف\n`;
  md += '\n';
}

md += `## محدودیت‌های این نمودار

1. **SQLite کلید خارجی را فقط با \`PRAGMA foreign_keys = ON\` اعمال می‌کند.**
   لاراول این را در هر اتصال روشن می‌کند؛ یک کوئری خارج از لاراول ممکن است نادیده
   بگیرد.
2. **همهٔ رابطه‌ها اعلان نشده‌اند.** چند ستون مثل \`contracts.renewed_from_id\`
   رابطه را در کد بیان می‌کنند. هر جا رابطهٔ اعلان‌نشده پیدا کردید، این نمودار
   آن را نشان نمی‌دهد.
3. **چندریختی جدول‌های پیوست** (\`attachments.attachable_type/id\`) با کلید خارجی
   قابل بیان نیست و در این نمودار یال ندارد.
4. **ستون‌ها در نمودار نیستند** تا خوانا بماند. فهرست ستون‌ها در
   [\`DATABASE_SCHEMA.md\`](../DATABASE_SCHEMA.md) است.

## وضعیت خروجی گراف‌ویز

فایل \`docs/database/erd.dot\` تولید شده و از نظر ساختاری بررسی شده است
(پرانتزهای متوازن، ۵۷ گره اعلان‌شده، ۹۳ یال، هیچ یالی با گرهٔ اعلان‌نشده).
**Graphviz در محیط توسعه نصب نیست**، پس خروجی تصویری تولید و بازبینی نشده است.
تصاویر قدیمی \`docs/diagrams/erd.{png,svg}\` مربوط به نمودار دستی قبلی‌اند و
نباید با این یکی اشتباه شوند.

## بازتولید تصویر

\`\`\`bash
dot -Tsvg docs/database/erd.dot -o docs/diagrams/erd.svg
dot -Tpng docs/database/erd.dot -o docs/diagrams/erd.png
\`\`\`
`;

fs.writeFileSync(path.join(ROOT, 'docs/ERD.md'), md, 'utf8');
console.log(`wrote docs/ERD.md and docs/database/erd.dot — ${tables.length} tables, ${edges.length} FKs`);
